/**
 * Provides auxiliary translations of the 100 civics questions in all supported languages
 * so the user can understand the English question in their native language (e.g. Chinese, French,
 * Vietnamese, Arabic, Swahili, Esperanto, Russian, Portuguese, etc.), while preserving the
 * rule that all official questions and answers are learned exclusively in English.
 */
object CivicsTranslations {

    fun getQuestionTranslation(questionId: Int, language: AppLanguage, fallbackSpanish: String? = null): String {
        return when (language) {
            AppLanguage.SPANISH -> fallbackSpanish ?: getSpanish(questionId)
            AppLanguage.CHINESE -> getChinese(questionId)
            AppLanguage.VIETNAMESE -> getVietnamese(questionId)
            AppLanguage.TAGALOG -> getTagalog(questionId)
            AppLanguage.ARABIC -> getArabic(questionId)
            AppLanguage.FRENCH -> getFrench(questionId)
            AppLanguage.KOREAN -> getKorean(questionId)
            AppLanguage.RUSSIAN -> getRussian(questionId)
            AppLanguage.PORTUGUESE -> getPortuguese(questionId)
            AppLanguage.HAITIAN_CREOLE -> getHaitianCreole(questionId)
            AppLanguage.HINDI -> getHindi(questionId)
            AppLanguage.PERSIAN -> getFarsi(questionId)
            AppLanguage.SWAHILI -> getSwahili(questionId)
            AppLanguage.ESPERANTO -> getEsperanto(questionId)
            AppLanguage.GERMAN -> getGerman(questionId)
            AppLanguage.ITALIAN -> getItalian(questionId)
            AppLanguage.POLISH -> getPolish(questionId)
            AppLanguage.JAPANESE -> getJapanese(questionId)
            AppLanguage.GUJARATI, AppLanguage.TELUGU, AppLanguage.BENGALI -> getHindi(questionId)
            AppLanguage.ENGLISH -> "" // English learners see direct English
        }
    }

